/**
 * @param {number} nums
 * @returns {number}
 */
const mostFrequentEven = nums => {
    const map = new Map();
    let maxFreq = 0;

    for (const num of nums) {
        if (num % 2 === 0) {
            const freq = (map.get(num) || 0) + 1;
            maxFreq = Math.max(maxFreq, freq);
            map.set(num, freq);
        }
    }

    let max = Infinity;

    for (const [num, freq] of map) {
        if (freq === maxFreq) {
            if (num < max) max = num;
        }
    }

    return max === Infinity ? -1 : max;
};

